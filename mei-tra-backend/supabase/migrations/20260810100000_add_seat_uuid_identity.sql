create or replace function meitra_private.resolve_room_seat_id(
  p_room_id uuid,
  p_identity_key text default null,
  p_user_id uuid default null
)
returns uuid
language sql
stable
security definer
set search_path = ''
as $function$
  select room_player.id
  from public.room_players as room_player
  where room_player.room_id = p_room_id
    and (
      (p_identity_key is not null and room_player.id::text = p_identity_key)
      or (
        p_identity_key is not null
        and room_player.player_id = p_identity_key
      )
      or (p_user_id is not null and room_player.user_id = p_user_id)
    )
  order by case
    when p_identity_key is not null
      and room_player.id::text = p_identity_key then 0
    when p_identity_key is not null
      and room_player.player_id = p_identity_key then 1
    else 2
  end
  limit 1;
$function$;

revoke all on function meitra_private.resolve_room_seat_id(uuid, text, uuid)
  from public, anon, authenticated;
grant execute on function meitra_private.resolve_room_seat_id(uuid, text, uuid)
  to service_role;

update public.rooms as room
set host_seat_id = meitra_private.resolve_room_seat_id(
  room.id,
  room.host_id,
  case
    when room.host_id ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
      then room.host_id::uuid
    else null
  end
)
where room.host_seat_id is null;

update public.game_states as game_state
set current_seat_id = meitra_private.resolve_room_seat_id(
  game_state.room_id,
  game_state.current_player_id,
  null
)
where game_state.current_seat_id is null
  and game_state.current_player_id is not null;

update public.game_history as history
set
  actor_key_snapshot = coalesce(history.actor_key_snapshot, history.player_id),
  actor_seat_id = coalesce(
    history.actor_seat_id,
    meitra_private.resolve_room_seat_id(
      history.room_id,
      history.player_id,
      null
    )
  )
where history.player_id is not null
   or history.actor_key_snapshot is not null;

update public.active_room_memberships as membership
set seat_id = meitra_private.resolve_room_seat_id(
  membership.room_id,
  membership.player_id,
  membership.user_id
)
where membership.room_id is not null
  and membership.seat_id is null;

update public.room_membership_events as event
set seat_id = meitra_private.resolve_room_seat_id(
  coalesce(event.to_room_id, event.from_room_id),
  null,
  event.user_id
)
where event.seat_id is null
  and coalesce(event.to_room_id, event.from_room_id) is not null;

