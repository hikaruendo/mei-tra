create or replace function public.reject_room_player_seat_id_change()
returns trigger
language plpgsql
security invoker
set search_path = public
as $function$
begin
  if new.id is distinct from old.id then
    raise exception 'room_player_seat_id_is_immutable room=% seat=%',
      old.room_id,
      old.id
      using errcode = 'PT422';
  end if;
  if new.room_id is distinct from old.room_id then
    raise exception 'room_player_room_id_is_immutable room=% seat=%',
      old.room_id,
      old.id
      using errcode = 'PT422';
  end if;
  if new.seat_index is distinct from old.seat_index then
    raise exception 'room_player_seat_index_is_immutable room=% seat=% index=%',
      old.room_id,
      old.id,
      old.seat_index
      using errcode = 'PT422';
  end if;

  return new;
end;
$function$;

drop trigger if exists reject_room_player_seat_id_change
  on public.room_players;

create trigger reject_room_player_seat_id_change
before update of id, room_id, seat_index on public.room_players
for each row execute function public.reject_room_player_seat_id_change();

create or replace function public.reject_room_player_seat_delete()
returns trigger
language plpgsql
security invoker
set search_path = public
as $function$
begin
  if exists (
    select 1
    from public.rooms
    where id = old.room_id
  ) then
    raise exception 'room_player_seat_delete_requires_room_delete room=% seat=%',
      old.room_id,
      old.id
      using errcode = 'PT422';
  end if;

  return old;
end;
$function$;

drop trigger if exists reject_room_player_seat_delete
  on public.room_players;

create trigger reject_room_player_seat_delete
before delete on public.room_players
for each row execute function public.reject_room_player_seat_delete();

