import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { styleDenshoSvg } from './densho-style.mjs';

const standard = new URL('../../../mei-tra-frontend/public/cards/', import.meta.url);
const originals = new URL('../assets/densho/', import.meta.url);
const output = new URL('styled/', originals);
const web = new URL('../../../mei-tra-frontend/public/cards/densho/styled/', import.meta.url);
const registry = new URL('../../../mei-tra-mobile/src/lib/densho-card-assets.ts', import.meta.url);
const revisionPath = new URL('../densho-revision.ts', import.meta.url);
const manifestPath = new URL('manifest.json', output);
const hash = data => createHash('sha256').update(data).digest('hex');
const check = process.argv.includes('--check');
const recipe = await readFile(new URL('./densho-style.mjs', import.meta.url));
const builder = await readFile(new URL('./build-densho-cards.mjs', import.meta.url));
const configBytes = await readFile(new URL('../densho-rendering.json', import.meta.url));
const config = JSON.parse(configBytes);
const ids = [...(await readdir(standard)).filter(file => /^(?:[2-9]|10|J|Q|K|A)_[SHDC]\.svg$/.test(file)).map(file => file.slice(0, -4)), 'card_back', 'joker_red'].sort();
const sizes = Object.entries(config.widths);
const fileFor = (id, size) => `${size === 'large' ? '' : `${size}/`}${id}.webp`;
const registrySource = `// Generated by build-densho-cards.mjs; do not edit.\nexport const DENSHO_STYLED_SOURCES: Record<string, Record<'small' | 'medium' | 'large', () => number>> = {\n${ids.map(id => `  ${JSON.stringify(id)}: {\n${sizes.map(([size]) => `    ${size}: () => require('@meitra/game-client/assets/densho/styled/${fileFor(id, size)}'),`).join('\n')}\n  },`).join('\n')}\n};\n`;
const recipeHash = hash(Buffer.concat([recipe, builder, configBytes]));
const manifest = check ? JSON.parse(await readFile(manifestPath, 'utf8')) : { recipe: recipeHash, cards: {} };
if (check && manifest.recipe !== recipeHash) throw new Error('Densho style recipe changed; rebuild assets.');
if (check && await readFile(registry, 'utf8') !== registrySource) throw new Error('Densho asset registry is stale.');
if (check && Object.keys(manifest.cards).join() !== ids.join()) throw new Error('Densho deck coverage is stale.');
let sharp;
if (!check) {
  const require = createRequire(new URL('../../../mei-tra-mobile/package.json', import.meta.url));
  sharp = require('sharp');
  for (const dir of [output, web]) {
    for (const [size] of sizes) await mkdir(new URL(size === 'large' ? './' : `${size}/`, dir), { recursive: true });
  }
}
let total = 0;
for (const id of ids) {
  const crop = config.originals[id];
  const source = await readFile(crop ? new URL(`${id}.jpg`, originals) : new URL(`${id}.svg`, standard));
  if (!check) manifest.cards[id] = { source: hash(source), assets: {} };
  if (check && manifest.cards[id].source !== hash(source)) throw new Error(`Stale source: ${id}`);
  for (const [size, width] of sizes) {
    const file = fileFor(id, size);
    const out = new URL(file, output);
    const copy = new URL(file, web);
    if (check) {
      const asset = await readFile(out);
      if (manifest.cards[id].assets[size] !== hash(asset)) throw new Error(`Stale densho card: ${file}`);
      if (!asset.equals(await readFile(copy))) throw new Error(`Web/mobile artwork differs: ${file}`);
      total += asset.length;
    } else {
      // Downsample once at build time, then restore only mild edge contrast at
      // thumbnail sizes. Preserve original artwork; never synthesize details.
      const input = crop ? sharp(source).extract(crop) : sharp(Buffer.from(styleDenshoSvg(source.toString())), { density: 216 });
      let render = input.resize(width, width * 1.5, { fit: 'fill', kernel: 'lanczos3' }).flatten({ background: '#ffffff' });
      if (size !== 'large') render = render.sharpen({ sigma: 0.4, m1: 0.5, m2: 1, x1: 2, y2: 5, y3: 5 });
      const asset = await render.webp({ lossless: true, effort: 6 }).toBuffer();
      await writeFile(out, asset);
      await writeFile(copy, asset);
      manifest.cards[id].assets[size] = hash(asset);
      total += asset.length;
    }
  }
}
if (total > 3 * 1024 * 1024) throw new Error('Densho cards exceed the 3 MB budget.');
// Changing any source, render recipe or image changes web cache keys together.
const revisionSource = `// Generated by build-densho-cards.mjs; do not edit.\nexport const DENSHO_ASSET_REVISION = '${hash(JSON.stringify(manifest)).slice(0, 12)}';\n`;
if (check && await readFile(revisionPath, 'utf8') !== revisionSource) throw new Error('Densho asset revision is stale.');
if (!check) {
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  await writeFile(registry, registrySource);
  await writeFile(revisionPath, revisionSource);
}
console.log(`${ids.length} densho cards, ${sizes.length} sizes ${check ? 'verified' : 'built'} (${(total / 1024).toFixed(0)} KB).`);
