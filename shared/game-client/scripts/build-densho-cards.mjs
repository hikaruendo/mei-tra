import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { styleDenshoSvg } from './densho-style.mjs';

const standard = new URL('../../../mei-tra-frontend/public/cards/', import.meta.url);
const output = new URL('../assets/densho/styled/', import.meta.url);
const web = new URL('../../../mei-tra-frontend/public/cards/densho/styled/', import.meta.url);
const registry = new URL('../../../mei-tra-mobile/src/lib/densho-card-assets.ts', import.meta.url);
const manifestPath = new URL('manifest.json', output);
const hash = data => createHash('sha256').update(data).digest('hex');
const check = process.argv.includes('--check');
const recipe = await readFile(new URL('./densho-style.mjs', import.meta.url));
const builder = await readFile(new URL('./build-densho-cards.mjs', import.meta.url));
const ids = (await readdir(standard)).filter(file => /^(?:[2-9]|10|J|Q|K|A)_[SHDC]\.svg$/.test(file) && file !== 'A_S.svg').map(file => file.slice(0, -4)).sort();
const registrySource = `// Generated by build-densho-cards.mjs; do not edit.\nexport const DENSHO_STYLED_SOURCES: Record<string, () => number> = {\n${ids.map(id => `  ${JSON.stringify(id)}: () => require('@meitra/game-client/assets/densho/styled/${id}.webp'),`).join('\n')}\n};\n`;
const manifest = check ? JSON.parse(await readFile(manifestPath, 'utf8')) : { recipe: hash(Buffer.concat([recipe, builder])), cards: {} };
if (check && manifest.recipe !== hash(Buffer.concat([recipe, builder]))) throw new Error('Densho style recipe changed; rebuild assets.');
if (check && await readFile(registry, 'utf8') !== registrySource) throw new Error('Densho asset registry is stale.');
if (check && Object.keys(manifest.cards).join() !== ids.join()) throw new Error('Densho deck coverage is stale.');
let sharp;
if (!check) {
  const require = createRequire(new URL('../../../mei-tra-mobile/package.json', import.meta.url));
  sharp = require('sharp');
  await mkdir(output, { recursive: true });
  await mkdir(web, { recursive: true });
}
let total = 0;
for (const id of ids) {
  const source = await readFile(new URL(`${id}.svg`, standard));
  const out = new URL(`${id}.webp`, output);
  const copy = new URL(`${id}.webp`, web);
  if (check) {
    const asset = await readFile(out);
    if (manifest.cards[id].source !== hash(source) || manifest.cards[id].asset !== hash(asset)) throw new Error(`Stale densho card: ${id}`);
    if (!asset.equals(await readFile(copy))) throw new Error(`Web/mobile artwork differs: ${id}`);
    total += asset.length;
  } else {
    const asset = await sharp(Buffer.from(styleDenshoSvg(source.toString())), { density: 216 })
      .resize(630, 945, { fit: 'fill' }).flatten({ background: '#ffffff' })
      .webp({ quality: 90 }).toBuffer();
    await writeFile(out, asset);
    await writeFile(copy, asset);
    manifest.cards[id] = { source: hash(source), asset: hash(asset) };
    total += asset.length;
  }
}
if (total > 3 * 1024 * 1024) throw new Error('Densho styled cards exceed the 3 MB budget.');
if (!check) {
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  await writeFile(registry, registrySource);
}
console.log(`${ids.length} densho cards ${check ? 'verified' : 'built'} (${(total / 1024).toFixed(0)} KB).`);
