#!/usr/bin/env node
/**
 * Builds the mobile card art from the web app's SVG source of truth.
 *
 * The web assets total ~7.7 MB, but they are not uniformly heavy: pip cards are
 * ~60 path nodes / 6-16 KB each, while the twelve court cards are Inkscape
 * traces of ~9,000 nodes / 0.6-1.1 MB each. SVGO reduces the *file size* of a
 * court card but not its node count, and react-native-svg pays that node cost
 * on every render at a 30-60px display size. So the pipeline splits:
 *
 *   pips + aces + joker + back  ->  SVGO-compressed .svg   (true vector)
 *   J / Q / K  (12 cards)       ->  3x .webp raster        (bounded cost)
 *
 * Rasterising the courts also side-steps a font problem: the rank indices are
 * `<text font-family="Arial">` nodes. iOS ships Arial so the vector cards match
 * the web, and the rasterised courts bake the glyphs in at build time.
 *
 * A build writes `assets/cards/manifest.json` alongside the art, recording the
 * SHA of each *source* SVG. `--check` compares those SHAs rather than the
 * generated bytes: webp encoding is only reproducible for a fixed
 * sharp/libvips build, so byte-comparing the twelve courts would report them
 * stale forever whenever CI's encoder differs from the machine that generated
 * the committed files. Hashing the inputs answers the question that actually
 * matters — "did the web art change without the mobile art being rebuilt?" —
 * and needs neither sharp nor svgo to run.
 *
 * Usage:
 *   node scripts/build-card-assets.mjs           # write assets + manifest
 *   node scripts/build-card-assets.mjs --check   # verify committed assets are current
 */
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const MOBILE = join(HERE, '..');
const SOURCE = join(MOBILE, '..', 'mei-tra-frontend', 'public', 'cards');
const DEST = join(MOBILE, 'assets', 'cards');

/** Court ranks are rasterised; everything else stays vector. */
const COURT_RANKS = new Set(['J', 'Q', 'K']);
/** cardToSvgId always resolves JOKER to joker_red, so the black one is dead. */
const EXCLUDED = new Set(['joker_black.svg']);

const MANIFEST_NAME = 'manifest.json';

/** 3x the 210x315 viewBox — ample for a card that renders at most ~72pt wide. */
const RASTER_SCALE = 3;
const RASTER_QUALITY = 85;

const MAX_FILE_BYTES = 450 * 1024;
const MAX_TOTAL_BYTES = 3 * 1024 * 1024;

const svgoConfig = {
  multipass: true,
  plugins: [
    {
      name: 'preset-default',
      params: {
        overrides: {
          // No removeViewBox override here: it is not part of preset-default in
          // svgo v4, so configuring it only produced a warning per file (42 of
          // them) and did nothing. The viewBox survives on its own, which
          // react-native-svg needs in order to scale the drawing — the test
          // asserts it rather than trusting this config.
          //
          // card_back.svg references url(#felt) / url(#glow) / url(#weave);
          // keep the names readable rather than minifying to a/b/c.
          cleanupIds: { remove: true, minify: false },
          convertPathData: { floatPrecision: 1, transformPrecision: 3 },
          cleanupNumericValues: { floatPrecision: 1 },
          // Court art is multi-colour; merging paths would flatten fills.
          mergePaths: false,
        },
      },
    },
    // Inkscape/sodipodi namespaced cruft is already handled by
    // preset-default's removeEditorsNSData.
    // Size comes from props, not the document.
    { name: 'removeDimensions' },
    { name: 'sortAttrs' },
  ],
};

const isCourt = (name) => COURT_RANKS.has(name.split('_')[0]);
const kb = (bytes) => `${(bytes / 1024).toFixed(1)}KB`;
const sha = (buf) => createHash('sha256').update(buf).digest('hex').slice(0, 12);

const outNameFor = (id) => `${id}.${isCourt(id) ? 'webp' : 'svg'}`;

/** Every card the web ships, which is the deck mobile must mirror exactly. */
async function sourceIds() {
  const files = (await readdir(SOURCE))
    .filter((f) => f.endsWith('.svg') && !EXCLUDED.has(f))
    .sort();
  return files.map((f) => f.replace(/\.svg$/, ''));
}

/** Generated art plus manifest.json; anything else in DEST is an orphan. */
async function destFiles() {
  return (await readdir(DEST).catch(() => []))
    .filter((f) => f !== MANIFEST_NAME)
    .sort();
}

async function build() {
  // Imported here rather than at module scope so `--check` — which runs in CI
  // on every PR — needs neither the native sharp binary nor svgo.
  const [{ default: sharp }, { optimize }] = await Promise.all([
    import('sharp'),
    import('svgo'),
  ]);

  const ids = await sourceIds();
  await mkdir(DEST, { recursive: true });

  const results = [];

  for (const id of ids) {
    const file = `${id}.svg`;
    const source = await readFile(join(SOURCE, file));
    const outName = outNameFor(id);
    const output = isCourt(id)
      ? await sharp(source, { density: 72 * RASTER_SCALE })
          .resize(210 * RASTER_SCALE, 315 * RASTER_SCALE, {
            fit: 'fill',
            background: { r: 0, g: 0, b: 0, alpha: 0 },
          })
          .webp({ quality: RASTER_QUALITY })
          .toBuffer()
      : Buffer.from(
          optimize(source.toString('utf8'), { ...svgoConfig, path: file }).data,
          'utf8',
        );

    if (output.length > MAX_FILE_BYTES) {
      throw new Error(
        `${outName} is ${kb(output.length)}, over the ${kb(MAX_FILE_BYTES)} budget`,
      );
    }

    await writeFile(join(DEST, outName), output);
    results.push({ id, outName, sourceSha: sha(source), out: output.length });
  }

  // A renamed or deleted source would otherwise leave its old output behind,
  // and the registry would keep shipping art the web no longer has.
  const expected = new Set(results.map((r) => r.outName));
  for (const file of await destFiles()) {
    if (expected.has(file)) continue;
    await unlink(join(DEST, file));
    console.log(`pruned orphan: ${file}`);
  }

  const totalOut = results.reduce((n, r) => n + r.out, 0);
  if (totalOut > MAX_TOTAL_BYTES) {
    throw new Error(
      `total ${kb(totalOut)} exceeds the ${kb(MAX_TOTAL_BYTES)} budget`,
    );
  }

  await writeFile(
    join(DEST, MANIFEST_NAME),
    `${JSON.stringify(
      {
        source: 'mei-tra-frontend/public/cards',
        cards: Object.fromEntries(
          results.map((r) => [r.id, { out: r.outName, sourceSha: r.sourceSha }]),
        ),
      },
      null,
      2,
    )}\n`,
  );

  const rasters = results.filter((r) => r.outName.endsWith('.webp'));
  const heaviest = [...results].sort((a, b) => b.out - a.out)[0];
  console.log(
    `${results.length} cards: ${results.length - rasters.length} vector, ${rasters.length} raster`,
  );
  console.log(`total ${kb(totalOut)}, heaviest ${heaviest.outName} ${kb(heaviest.out)}`);
}

async function check() {
  const manifest = JSON.parse(
    await readFile(join(DEST, MANIFEST_NAME), 'utf8').catch(() => {
      throw new Error(`${MANIFEST_NAME} is missing — run npm run assets:cards`);
    }),
  );
  const problems = [];

  const ids = await sourceIds();
  for (const id of ids) {
    if (!manifest.cards[id]) {
      problems.push(`${id}: new source card, never built`);
    }
  }

  for (const [id, entry] of Object.entries(manifest.cards)) {
    const source = await readFile(join(SOURCE, `${id}.svg`)).catch(() => null);
    if (!source) {
      problems.push(`${id}: source card is gone, but its art is still shipped`);
      continue;
    }
    if (sha(source) !== entry.sourceSha) {
      problems.push(`${id}: web art changed since the mobile art was built`);
    }
    const built = await readFile(join(DEST, entry.out)).catch(() => null);
    if (!built) problems.push(`${entry.out}: missing`);
  }

  const listed = new Set(Object.values(manifest.cards).map((e) => e.out));
  for (const file of await destFiles()) {
    if (!listed.has(file)) problems.push(`${file}: not in the manifest`);
  }

  if (problems.length > 0) {
    for (const problem of problems) console.error(`  ${problem}`);
    throw new Error(
      `${problems.length} card asset problem(s) — run npm run assets:cards`,
    );
  }

  console.log(`${ids.length} card assets up to date`);
}

const run = process.argv.includes('--check') ? check : build;

run().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
